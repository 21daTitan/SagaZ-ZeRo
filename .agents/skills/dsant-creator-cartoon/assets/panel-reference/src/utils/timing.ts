import vo from '../data/vo.json';
import timing from '../data/timing.json';
export const FPS=30,WIDTH=1080,HEIGHT=1920,SECONDS=40,DURATION=1200;
export const f=(s:number)=>Math.round(s*FPS);
export const s=f;
export const VO_KEYS=['s1','s2','s3','s4','s5','s6','s7'] as const;
export type VoKey=typeof VO_KEYS[number];
export const HAS_VO=true;
export const VO_START=timing.starts;
export const SCENE_FRAMES=VO_KEYS.map((_,i)=>({from:timing.bounds[i],durationInFrames:timing.bounds[i+1]-timing.bounds[i]}));
export const voWords=(key:VoKey)=>vo[key].words;
export const wordLocal=(key:VoKey,index:number)=>f(VO_START[key]+(vo[key].words[index]?.start??0))-SCENE_FRAMES[VO_KEYS.indexOf(key)].from;
export const voLocal=(key:VoKey)=>f(VO_START[key])-SCENE_FRAMES[VO_KEYS.indexOf(key)].from;
export const VO=VO_KEYS.map(id=>({id,at:VO_START[id],seconds:vo[id].seconds,text:vo[id].text}));
if(timing.speechEnd>37)throw new Error('A voz invade os 3 segundos de contato final');
